import { rolesFor } from "@/components/admin/nav";
import { getCurrentUser } from "@/lib/server/auth";
import { db } from "@/lib/server/db";
import { readFile } from "@/lib/server/file-store";

/** Enquiry attachments: signed-in staff only, always downloaded (never rendered inline). */
export async function GET(_request: Request, { params }: { params: Promise<{ id: string }> }) {
  const user = await getCurrentUser();
  if (!user || !rolesFor("/admin/leads/").includes(user.role)) return new Response("Sign in required", { status: 401 });
  const upload = await db.upload.findUnique({ where: { id: (await params).id } });
  if (!upload) return new Response("Not found", { status: 404 });
  // storedName is generated by us; readFile still keeps only the base name.
  const body = await readFile("uploads", upload.storedName);
  if (!body) return new Response("File missing on the server", { status: 410 });
  return new Response(body as BodyInit, {
    headers: {
      "content-type": upload.mimeType,
      "content-disposition": `attachment; filename="${upload.originalName.replace(/"/g, "")}"`,
      "x-content-type-options": "nosniff",
      "cache-control": "private, no-store",
    },
  });
}
