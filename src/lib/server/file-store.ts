// Where files live. Local disk by default (Docker/VPS); Vercel Blob when a Blob store is
// connected (Vercel's own disk does not keep files). Every file is private either way:
// visitors only reach them through /files/[key] and /admin/uploads/[id].
import "server-only";
import fs from "node:fs/promises";
import path from "node:path";
import { del, get, put } from "@vercel/blob";

export type Area = "media" | "uploads";

export const usingBlob = () => Boolean(process.env.BLOB_READ_WRITE_TOKEN);

// Runtime-configured folders: tell the bundler not to trace (and package) the whole project from them.
export const mediaDir = () => path.resolve(/*turbopackIgnore: true*/ process.env.MEDIA_DIR ?? "storage/media");
export const uploadDir = () => path.resolve(/*turbopackIgnore: true*/ process.env.UPLOAD_DIR ?? "storage/uploads");
const dirFor = (area: Area) => (area === "media" ? mediaDir() : uploadDir());

/** Keys are generated by us; still, never let one become a path. */
const safeKey = (key: string) => path.basename(key);

export async function writeFile(area: Area, key: string, bytes: Uint8Array, contentType: string) {
  if (usingBlob()) {
    await put(`${area}/${safeKey(key)}`, Buffer.from(bytes), { access: "private", contentType, addRandomSuffix: false });
    return;
  }
  const dir = dirFor(area);
  await fs.mkdir(/*turbopackIgnore: true*/ dir, { recursive: true, mode: 0o750 });
  await fs.writeFile(path.join(/*turbopackIgnore: true*/ dir, safeKey(key)), bytes, { mode: area === "media" ? 0o644 : 0o640, flag: "wx" });
}

/** The file's contents as a stream, or null if it is missing. */
export async function readFile(area: Area, key: string): Promise<ReadableStream<Uint8Array> | Uint8Array | null> {
  if (usingBlob()) {
    const res = await get(`${area}/${safeKey(key)}`, { access: "private" }).catch(() => null);
    return res?.statusCode === 200 ? res.stream : null;
  }
  const body = await fs.readFile(path.join(/*turbopackIgnore: true*/ dirFor(area), safeKey(key))).catch(() => null);
  return body ? new Uint8Array(body) : null;
}

export async function removeFiles(area: Area, keys: string[]) {
  if (keys.length === 0) return;
  if (usingBlob()) {
    await del(keys.map((k) => `${area}/${safeKey(k)}`)).catch((e) => console.error("Blob delete failed", e));
    return;
  }
  await Promise.all(keys.map((k) => fs.rm(path.join(/*turbopackIgnore: true*/ dirFor(area), safeKey(k)), { force: true })));
}
